package aihelper

import (
	"bufio"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"testing"
)

var updateRouteDocs = flag.Bool("update", false, "rewrite apidocs_gen.go from docs/reference/api.md")

var getRow = regexp.MustCompile("^\\|\\s*GET\\s*\\|\\s*`([^`]+)`\\s*\\|\\s*(.*?)\\s*\\|\\s*[^|]*\\|\\s*$")

// referenceRouteDocs reads every GET row of docs/reference/api.md.
func referenceRouteDocs(t *testing.T) map[string]string {
	t.Helper()
	f, err := os.Open("../../../docs/reference/api.md")
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	out := map[string]string{}
	scan := bufio.NewScanner(f)
	scan.Buffer(make([]byte, 1<<20), 1<<20)
	for scan.Scan() {
		// A cell's literal pipe is written \|; read it as one before the
		// row is split on the unescaped ones.
		line := strings.ReplaceAll(scan.Text(), `\|`, "\x00")
		m := getRow.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		key := normalizeRoute(m[1])
		if !strings.HasPrefix(key, "/api/v1/") {
			continue
		}
		out[key] = strings.ReplaceAll(m[2], "\x00", "|")
	}
	if err := scan.Err(); err != nil {
		t.Fatal(err)
	}
	return out
}

// The assistant's route catalog is the API reference's own wording, so a
// route documented for people is documented for the assistant too.
func TestRouteDocsMatchAPIReference(t *testing.T) {
	want := referenceRouteDocs(t)
	if len(want) < 80 {
		t.Fatalf("read only %d GET rows from docs/reference/api.md; the row format changed", len(want))
	}
	if *updateRouteDocs {
		keys := make([]string, 0, len(want))
		for k := range want {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		var b strings.Builder
		b.WriteString("// Code generated by TestRouteDocsMatchAPIReference -update from docs/reference/api.md; DO NOT EDIT.\n\npackage aihelper\n\nvar routeDocs = map[string]string{\n")
		for _, k := range keys {
			fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(k), strconv.Quote(want[k]))
		}
		b.WriteString("}\n")
		src, err := format.Source([]byte(b.String()))
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile("apidocs_gen.go", src, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	for k, v := range want {
		if routeDocs[k] != v {
			t.Fatalf("apidocs_gen.go is out of date with docs/reference/api.md at %s; regenerate: go test ./internal/server/aihelper -run TestRouteDocsMatchAPIReference -update", k)
		}
	}
	if len(routeDocs) != len(want) {
		t.Fatalf("apidocs_gen.go has %d routes, docs/reference/api.md %d; regenerate it", len(routeDocs), len(want))
	}
}

func TestRouteDocLooksUpAnyParameterSpelling(t *testing.T) {
	for _, pattern := range []string{"/api/v1/nodes/{uuid}", "/api/v1/nodes/{id}", "/api/v1/nodes/*"} {
		if RouteDoc(pattern) == "" {
			t.Fatalf("RouteDoc(%q) is empty", pattern)
		}
	}
	if RouteDoc("/api/v1/inference-templates/yaml") == "" {
		t.Fatal("a route documented with its query string is not found by its path")
	}
	if RouteDoc("/api/v1/no/such/route") != "" {
		t.Fatal("RouteDoc found an undocumented route")
	}
}
