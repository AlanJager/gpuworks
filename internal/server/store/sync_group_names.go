package store

import (
	"errors"
	"fmt"
)

const syncGroupNameMaxBytes = 64

func duplicateSyncGroupName() error {
	return pullSettingReasonError("name", "name_duplicate", fmt.Errorf("a sync group with this name already exists"), nil)
}

// The precheck gives immediate field feedback. The unique index is still the
// authority if another writer takes this name before our transaction commits.
func (s *Store) checkSyncGroupName(name string, exceptID uint) error {
	var count int64
	if err := s.db.Model(&SyncGroup{}).Where("name = ? AND id <> ?", name, exceptID).Count(&count).Error; err != nil {
		return err
	}
	if count > 0 {
		return duplicateSyncGroupName()
	}
	return nil
}

// Called only for a sync_groups insert/name update: its only unique value
// generated by the caller is the name. Use SQLite's typed extended result,
// without tying the store to a second driver or parsing English error text.
func syncGroupWriteError(err error) error {
	var coded interface{ Code() int }
	if errors.As(err, &coded) && coded.Code() == 2067 { // SQLITE_CONSTRAINT_UNIQUE
		return duplicateSyncGroupName()
	}
	return err
}
