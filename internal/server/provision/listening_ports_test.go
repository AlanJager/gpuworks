import "testing"

// The listeners of a Vast instance (vastai/base-image, 2026-10-19), plus one
// established connection: Jupyter on 8080, sshd on 22, Caddy on 8384, 6006
// and 1111, Syncthing on 18204, the portal on loopback ports. Its mapped
// ports 10100 and 10200 are free.
func TestParseListeningPortsReadsListenersOnly(t *testing.T) {
	out := `  sl  local_address rem_address   st tx_queue rx_queue tr tm->when retrnsmt   uid  timeout inode
   0: 0100007F:2B67 00000000:0000 0A 00000000:00000000 00:00000000 00000000     0        0 394532672 1 0000000000000000 100 0 0 10 0
   3: 00000000:1F90 00000000:0000 0A 00000000:00000000 00:00000000 00000000     0        0 394562592 1 0000000000000000 100 0 0 10 0
   4: 00000000:0016 00000000:0000 0A 00000000:00000000 00:00000000 00000000     0        0 394551629 1 0000000000000000 100 0 0 10 0
   6: 0200000A:2774 0100000A:C350 01 00000000:00000000 02:00012AB3 00000000     0        0 0 2 0000000000000000 20 4 30 10 -1
  sl  local_address                         remote_address                        st tx_queue rx_queue tr tm->when retrnsmt   uid  timeout inode
   0: 00000000000000000000000000000000:20C0 00000000000000000000000000000000:0000 0A 00000000:00000000 00:00000000 00000000     0        0 394549788 1 0000000000000000 100 0 0 10 0
   1: 00000000000000000000000000000000:1776 00000000000000000000000000000000:0000 0A 00000000:00000000 00:00000000 00000000     0        0 394549787 1 0000000000000000 100 0 0 10 0
   2: 00000000000000000000000000000000:0457 00000000000000000000000000000000:0000 0A 00000000:00000000 00:00000000 00000000     0        0 394549786 1 0000000000000000 100 0 0 10 0
   4: 00000000000000000000000000000000:471C 00000000000000000000000000000000:0000 0A 00000000:00000000 00:00000000 00000000  1001        0 394504955 2 0000000000000000 100 0 0 10 0
`
	got := parseListeningPorts(out)
	for _, port := range []int{11111, 8080, 22, 8384, 6006, 1111, 18204} {
		if !got[port] {
			t.Errorf("port %d not listed: %v", port, got)
		}
	}
	if got[10100] || got[10200] || len(got) != 7 {
		t.Fatalf("listening ports = %v", got)
	}
}
