// until polls until the condition holds. It is used instead of waitFor because
// the assertions here are about what the wizard sent, and antd's own modal
// teardown depends on transitions jsdom does not run to completion.
async function until(predicate: () => boolean, what: string) {
	for (let attempt = 0; attempt < 100; attempt++) {
		if (predicate()) return;
		await new Promise((resolve) => setTimeout(resolve, 20));
	}
	throw new Error(`timed out waiting for ${what}`);
}
