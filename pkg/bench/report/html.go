func htmlReport(run Run, dataset datasetConfig, target targetSnapshot, rows []pointRow) []byte {
	var out strings.Builder
	out.WriteString("<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">")
	fmt.Fprintf(&out, "<title>%s</title>", html.EscapeString(run.Name))
	out.WriteString(`<style>body{font:14px/1.55 system-ui,-apple-system,sans-serif;color:#172033;max-width:1180px;margin:36px auto;padding:0 24px}h1{font-size:28px}h2{margin-top:30px;border-bottom:1px solid #d9e0ea;padding-bottom:6px}blockquote{margin:16px 0;padding:12px 16px;background:#eef6ff;border-left:4px solid #1677ff}section,details{margin-top:14px}summary{cursor:pointer;font-weight:600}.timeline{overflow:auto;max-height:700px}td{overflow-wrap:anywhere}table{display:block;overflow:auto;border-collapse:collapse;width:100%;font-size:12px}th,td{border:1px solid #d9e0ea;padding:7px 8px;text-align:right}th:first-child,td:first-child{text-align:left}th{background:#f5f7fa}code,pre{font-family:ui-monospace,SFMono-Regular,monospace}pre{background:#f5f7fa;padding:12px;overflow:auto}.chart{border:1px solid #d9e0ea;border-radius:6px;padding:12px}.muted{color:#667085}@media print{body{margin:0;max-width:none}.chart{break-inside:avoid}a{color:inherit}}</style></head><body>`)
	fmt.Fprintf(&out, "<h1>%s</h1><blockquote>%s</blockquote>", html.EscapeString(run.Name), html.EscapeString(summary(run, dataset, rows)))
	if run.EvaluationURL != "" {
		fmt.Fprintf(&out, `<p><strong>Evaluation:</strong> <a href="%s">%s</a></p>`, html.EscapeString(run.EvaluationURL), html.EscapeString(run.EvaluationURL))
	}
	out.WriteString("<h2>Run</h2><table><tbody>")
	for _, property := range runProperties(run, dataset, target) {
		fmt.Fprintf(&out, "<tr><th>%s</th><td>%s</td></tr>", html.EscapeString(property[0]), html.EscapeString(orDash(property[1])))
	}
	out.WriteString("</tbody></table><h2>Recommendation conditions</h2>")
	writePropertiesHTML(&out, recommendationProperties(run, rows))
	out.WriteString("<h2>Throughput and interactivity</h2><div class=\"chart\">")
	out.WriteString(svgChart(rows))
	out.WriteString("</div><h2>Point results</h2><table><thead><tr>")
	for _, column := range columns[:20] {
		fmt.Fprintf(&out, "<th>%s</th>", html.EscapeString(column))
	}
	out.WriteString("</tr></thead><tbody>")
	for _, row := range rows {
		out.WriteString("<tr>")
		for _, value := range rowValues(row)[:20] {
			fmt.Fprintf(&out, "<td>%s</td>", html.EscapeString(value))
		}
		out.WriteString("</tr>")
	}
	out.WriteString("</tbody></table>")
	writeWarmupHTML(&out, run)
	writeEvidenceHTML(&out, rows)
	targetRows := targetProperties(target)
	if len(targetRows) > 0 || len(target.Env) > 0 {
		out.WriteString("<h2>Target snapshot</h2><table><tbody>")
		for _, property := range targetRows {
			fmt.Fprintf(&out, "<tr><th>%s</th><td>%s</td></tr>", html.EscapeString(property[0]), html.EscapeString(property[1]))
		}
		out.WriteString("</tbody></table>")
	}
	if len(target.Env) > 0 {
		out.WriteString("<h3>Environment</h3><pre>")
		for _, pair := range redactedEnv(target.Env) {
			fmt.Fprintf(&out, "%s=%s\n", html.EscapeString(pair[0]), html.EscapeString(pair[1]))
		}
		out.WriteString("</pre>")
	}
	out.WriteString("<h2>Metric definitions</h2><ul>")
	for _, definition := range metricDefinitions {
		fmt.Fprintf(&out, "<li>%s</li>", codeSpans(html.EscapeString(definition)))
	}
	if dataset.Kind == "agentic" {
		out.WriteString("<li>The designed prefix reuse rate describes the synthetic workload; it is not the observed cache hit rate.</li>")
	}
	out.WriteString("</ul>")
	if len(run.Warnings) > 0 {
		out.WriteString("<h2>Warnings</h2><ul>")
		for _, warning := range run.Warnings {
			fmt.Fprintf(&out, "<li><code>%s</code></li>", html.EscapeString(warning))
		}
		out.WriteString("</ul>")
	}
	out.WriteString("<p class=\"muted\">Generated by GPUWorks. This standalone report contains no external resources or JavaScript.</p></body></html>")
	return []byte(out.String())
}

func svgChart(rows []pointRow) string {
	observed := make([]pointRow, 0, len(rows))
	for _, row := range rows {
		if row.Interactivity > 0 && !tokenAggregatesUnavailable(row) {
			observed = append(observed, row)
		}
	}
	if len(observed) == 0 {
		return "<p>Chart unavailable: no observable decode interactivity. Unknown TPOT is not a zero-speed observation.</p>"
	}
	rows = observed
	const width, height, left, top, plotWidth, plotHeight = 760.0, 360.0, 76.0, 24.0, 650.0, 270.0
	maxX, maxY := 1.0, 1.0
	for _, row := range rows {
		maxX = math.Max(maxX, row.Interactivity)
		maxY = math.Max(maxY, row.OutputTput)
	}
	ordered := append([]pointRow(nil), rows...)
	sort.Slice(ordered, func(i, j int) bool { return ordered[i].Interactivity < ordered[j].Interactivity })
	coord := func(row pointRow) (float64, float64) {
		return left + row.Interactivity/maxX*plotWidth, top + plotHeight - row.OutputTput/maxY*plotHeight
	}
	var out strings.Builder
	fmt.Fprintf(&out, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %.0f %.0f" role="img" aria-label="Throughput and interactivity chart">`, width, height)
	out.WriteString(`<rect width="100%" height="100%" fill="white"/><line x1="76" y1="294" x2="726" y2="294" stroke="#98a2b3"/><line x1="76" y1="24" x2="76" y2="294" stroke="#98a2b3"/>`)
	if len(ordered) > 1 {
		out.WriteString(`<polyline fill="none" stroke="#1677ff" stroke-width="2" points="`)
		for _, row := range ordered {
			x, y := coord(row)
			fmt.Fprintf(&out, "%.1f,%.1f ", x, y)
		}
		out.WriteString(`"/>`)
	}
	for _, row := range rows {
		x, y := coord(row)
		fmt.Fprintf(&out, `<circle cx="%.1f" cy="%.1f" r="5" fill="#1677ff"/><text x="%.1f" y="%.1f" font-size="11" fill="#344054">%s</text>`, x, y, x+7, y-7, html.EscapeString(pointLabel(row.Point)))
	}
	fmt.Fprintf(&out, `<text x="401" y="342" text-anchor="middle" font-size="12">Interactivity, 1000 / TPOT P50 (tok/s/user), max %.1f</text>`, maxX)
	fmt.Fprintf(&out, `<text x="16" y="159" transform="rotate(-90 16 159)" text-anchor="middle" font-size="12">Output throughput (tok/s), max %.1f</text>`, maxY)
	out.WriteString(`</svg><p class="muted">Only points with observable decode interactivity are plotted.</p>`)
	return out.String()
}

var codeSpan = regexp.MustCompile("`([^`]+)`")

// codeSpans turns markdown code spans of already-escaped text into <code>.
func codeSpans(escaped string) string { return codeSpan.ReplaceAllString(escaped, "<code>$1</code>") }
